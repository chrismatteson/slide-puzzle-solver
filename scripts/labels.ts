// Runtime checks for board labels: eval label files and the real-photo manifest are hand-written or
// generated outside the type system, so nothing about them is trusted until checked here.

import { type GridSize } from "../src/puzzle/board.ts";
import { type Point, type Quad } from "../src/vision/geometry.ts";

export interface BoardLabel {
  size: 3 | 4;
  state: number[];
  solvable?: boolean;
  corners?: [number, number][];
  font?: string;
}

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

function readCorners(value: unknown, where: string): [number, number][] {
  if (!Array.isArray(value) || value.length !== 4)
    throw new Error(`${where}: corners must be 4 [x, y] pairs`);
  return value.map((pair: unknown): [number, number] => {
    if (!Array.isArray(pair) || pair.length !== 2)
      throw new Error(`${where}: corners must be 4 [x, y] pairs`);
    const x: unknown = pair[0];
    const y: unknown = pair[1];
    if (
      typeof x !== "number" ||
      typeof y !== "number" ||
      !Number.isFinite(x) ||
      !Number.isFinite(y)
    )
      throw new Error(`${where}: corners must be finite numbers`);
    return [x, y];
  });
}

/** Checks a parsed label and returns it typed; throws `<where>: <what is wrong>` otherwise. */
export function parseBoardLabel(raw: unknown, where: string): BoardLabel {
  if (!isRecord(raw)) throw new Error(`${where}: label must be a JSON object`);
  const { size, state, solvable, corners, font } = raw;
  if (size !== 3 && size !== 4) throw new Error(`${where}: size must be 3 or 4`);
  if (!Array.isArray(state)) throw new Error(`${where}: state must be an array`);
  const values: number[] = [];
  const items: unknown[] = state;
  for (const value of items) {
    if (typeof value !== "number" || !Number.isInteger(value))
      throw new Error(`${where}: state must hold integers only`);
    values.push(value);
  }
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length !== size * size || sorted.some((v, i) => v !== i))
    throw new Error(`${where}: state is not a permutation of 0..${String(size * size - 1)}`);
  const label: BoardLabel = { size, state: values };
  if (solvable !== undefined) {
    if (typeof solvable !== "boolean") throw new Error(`${where}: solvable must be true or false`);
    label.solvable = solvable;
  }
  if (corners !== undefined) label.corners = readCorners(corners, where);
  if (font !== undefined) {
    if (typeof font !== "string") throw new Error(`${where}: font must be a string`);
    label.font = font;
  }
  return label;
}

/** The label of a generated picture photo (scripts/gen_picture_photos.py, gen_correction_photos.py). */
export interface PictureLabel {
  size: GridSize;
  blank: number;
  solved: number[];
  tilesQuad: Quad;
  /** Only the correction sets with a printed solved picture have it. */
  thumbQuad?: Quad;
}

function readQuad(raw: unknown, where: string): Quad {
  if (!Array.isArray(raw) || raw.length !== 4) throw new Error(`${where} must have 4 corners`);
  const points = raw.map((corner: unknown): Point => {
    // Generated by the gen_*_photos.py scripts: {x, y} objects.
    if (!isRecord(corner)) throw new Error(`${where} corners must be {x, y} objects`);
    const { x, y } = corner;
    if (
      typeof x !== "number" ||
      typeof y !== "number" ||
      !Number.isFinite(x) ||
      !Number.isFinite(y)
    )
      throw new Error(`${where} corners must have finite x and y`);
    return { x, y };
  });
  // map gives Point[]; the length was checked to be 4 above.
  return points as unknown as Quad;
}

/** Checks a parsed picture label and returns it typed; throws `<where>: <what is wrong>` otherwise. */
export function parsePictureLabel(raw: unknown, where: string): PictureLabel {
  if (!isRecord(raw)) throw new Error(`${where}: label must be an object`);
  const { size, blank, solved, tilesQuad, thumbQuad } = raw;
  if (size !== 3 && size !== 4) throw new Error(`${where}: size must be 3 or 4`);
  if (typeof blank !== "number") throw new Error(`${where}: blank must be a number`);
  if (!Array.isArray(solved) || solved.length !== size * size)
    throw new Error(`${where}: solved must have ${String(size * size)} entries`);
  const solvedCells: number[] = [];
  const entries: unknown[] = solved;
  for (const cell of entries) {
    if (typeof cell !== "number" || !Number.isInteger(cell))
      throw new Error(`${where}: solved must hold integers only`);
    solvedCells.push(cell);
  }
  return {
    size,
    blank,
    solved: solvedCells,
    tilesQuad: readQuad(tilesQuad, `${where}: tilesQuad`),
    ...(thumbQuad === undefined ? {} : { thumbQuad: readQuad(thumbQuad, `${where}: thumbQuad`) }),
  };
}
